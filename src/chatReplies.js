function stableVariant(text, count) {
  let hash = 0;
  for (const character of text) hash = (hash * 31 + character.charCodeAt(0)) >>> 0;
  return count > 1 ? hash % count : 0;
}

export function getSweetReply(value) {
  const text = String(value || "").trim();
  const rule = replyRules.find(([pattern]) => pattern.test(text));
  if (!rule) return "嗯嗯，我在认真听呢。谢谢你愿意告诉我，靠近一点，我想陪你多待一会儿。";
  const replies = rule[1];
  return replies[stableVariant(text, replies.length)];
}
